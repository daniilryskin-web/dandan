def run():
    total = len(CASES)
    passed = 0
    rows = []
    for card, subj, cert, expected, note in CASES:
        verdict, score, _ = compare_product_names(card, cert, subject=subj, doc_status="Действует")
        ok = verdict == expected
        passed += ok
        rows.append((ok, expected, verdict, round(score, 1), note, card[:34]))
    print(f"{'res':4} {'ожидание':22} {'факт':22} {'score':6} {'кейс'}")
    print("-" * 100)
    for ok, exp, got, sc, note, card in rows:
        mark = "PASS" if ok else "FAIL"
        print(f"{mark:4} {exp:22} {got:22} {sc:<6} {note} | {card}")
    print("-" * 100)
    print(f"ИТОГО: {passed}/{total} прошло ({100*passed//total}%)")
    return passed, total


if __name__ == "__main__":
    p, t = run()
    sys.exit(0 if p == t else 1)
