/**
 * DataLens · Advanced-чарт · вкладка Controls
 *
 * Элементы управления внутри самого чарта. Они живут отдельно от селекторов
 * дашборда: рисуются в шапке виджета, влияют только на этот чарт и
 * сбрасываются при перезагрузке страницы.
 *
 * Здесь один контрол — поиск сотрудника по ФИО. Он не селектор дашборда
 * намеренно: искать человека нужно из самого дерева, не занимая место на
 * дашборде и не мешая остальным чартам.
 *
 * Как это работает:
 *   1. Человек вводит кусок фамилии или табельный номер.
 *   2. updateOnChange отправляет значение в параметр search.
 *   3. Вкладка Prepare читает его через Editor.getParams() и оставляет
 *      только те продукты, где этот человек есть — в команде, руководителем
 *      или заместителем.
 *
 * ВАЖНО. Параметр search обязан быть объявлен на вкладке Params, иначе
 * значение до чарта не дойдёт.
 *
 * Формат вкладки: объект с массивом controls. Обязательные поля контрола —
 * type и param.
 */

module.exports = {
    controls: [
        {
            type: 'input',
            param: 'search',
            label: 'Поиск сотрудника',
            labelPlacement: 'left',
            placeholder: 'фамилия или табельный номер',
            width: 260,
            // Перерисовать чарт сразу после ввода. Без этого значение
            // запишется в параметр, но дерево останется прежним.
            updateOnChange: true
        }
    ]
};
