# История срезов
# --------------------------------------------------------------------------

# Порядок событий на листе «Изменения»: сначала то, из-за чего меняются
# деньги и состав, потом перестановки, потом вакансии.
EVENT_ORDER = [
    # Лист «Изменения» — движение людей и денег, строго в этом порядке:
    # по нему выстраивается лесенка ФОТ.
    "Ушёл", "Пришёл", "ЗП изменилась",
    "Роль изменилась", "Руководитель изменился", "Продукты изменились",
    "Изменений нет",
    # Лист «Изменения · прочее»
    "⚠ Проверьте нумерацию", "Сотрудников", "Открытых вакансий",
    "Вакансия закрыта", "Вакансия открыта", "Вакансия висит",
]

CHANGE_COLUMNS = [
    "Дата среза", "Предыдущий срез", "Событие", "Сотрудник", "Блок", "Проект",
    "Продукт", "Было", "Стало", "Δ руб", "Δ %", "Комментарий",
]

# Доля состава, смена которой за один срез означает скорее перетасовку
# идентификаторов, чем реальное движение людей.
SHUFFLE_ALERT = 0.20


def read_snapshot(path: Path) -> pd.DataFrame:
    """Читает архивный срез, сохраняя «Сотрудник» строкой.

    Без явного типа pandas превратит «40» в 40.0, и тот же человек в двух
    срезах перестанет совпадать сам с собой.
    """
    return pd.read_csv(path, dtype={"Сотрудник": str}, keep_default_na=True)


def people_view(df: pd.DataFrame) -> pd.DataFrame:
    """Один человек — одна строка. То, что имеет смысл сравнивать между срезами.

    «Где работает» перечисляется целиком через «; »: у человека может быть
    несколько продуктов, проектов и руководителей, и в одну ячейку берётся
    не первичное назначение, а все. Продукт — коротким названием: полное
    «Проект / Продукт» дублировало бы соседний столбец «Проект».
    """
    people = df[df["Вакансия"] == 0]
    primary = people[people["Первичное назначение"] == 1].drop_duplicates("Сотрудник")
    primary = primary.set_index("Сотрудник")

    def joined(column: str) -> pd.Series:
        return people.groupby("Сотрудник")[column].agg(
            lambda values: "; ".join(
                sorted({str(v).strip() for v in values if str(v).strip()})
            )
        ).reindex(primary.index).fillna("")

    return pd.DataFrame({
        "ЗП": primary["ЗП"],
        "Проектная роль": primary["Проектная роль"],
        "Блок": joined("Блок"),
        "Проект": joined("Проект"),
        "Руководитель": joined("Руководитель"),
        "Продукты": joined("Продукт кратко"),
    })


def vacancy_view(df: pd.DataFrame) -> pd.Series:
    """Открытые позиции, свёрнутые до «где и кем»: сколько таких на срезе."""
    vacancies = df[df["Вакансия"] == 1]
    return vacancies.groupby(
        ["Блок", "Проект", "Продукт кратко", "Проектная роль"]
    ).size()


def vacancy_streaks(history: dict[str, pd.DataFrame],
                    until: str | None = None) -> dict[tuple, int]:
    """Сколько срезов подряд, считая от последнего, позиция остаётся открытой.

    Вакансия, висящая четвёртый месяц, — это либо ненужная позиция, либо не та
    вилка. На одном срезе это неразличимо: там она выглядит одинаково и в
    первый день, и в двухсотый.
    """
    dates = [d for d in sorted(history) if until is None or d <= until]
    views = {date: vacancy_view(history[date]) for date in dates}
    streaks: dict[tuple, int] = {}
    for key in views[dates[-1]].index:
        streak = 0
        for date in reversed(dates):
            if key in views[date].index:
                streak += 1
            else:
                break
        streaks[key] = streak
    return streaks


def money_text(value) -> str:
    """Сумма с пробелами между разрядами — для подписей внутри ячейки."""
    if value is None or pd.isna(value):
        return "—"
    return f"{round(float(value)):,}".replace(",", " ") + " ₽"


def changes_between(
    history: dict[str, pd.DataFrame], was: str, now: str
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Что изменилось между двумя соседними срезами.

    Возвращает два листа.

    Первый — движение людей и денег, выстроенное лесенкой: «Было» и «Стало» —
    это ФОТ до и после каждого события, а не зарплата одного человека. Строки
    идут подряд, поэтому «Стало» предыдущей равно «Было» следующей, а «Стало»
    последней строки — это новый ФОТ. Видно не только кто ушёл, но и на сколько
    от этого просел фонд — сразу в рублях и процентах.

    Второй — всё, что к ФОТ отношения не имеет: численность, вакансии
    и предупреждения о целостности истории.

    Что именно изменилось у человека (роль, зарплата, продукты), написано
    в «Комментарии»: столбцы «Было» и «Стало» заняты фондом.
    """
    build = CHANGE_COLUMNS + ["_вес"]
    before, after = people_view(history[was]), people_view(history[now])

    people_rows: list[dict] = []
    other_rows: list[dict] = []

    def add(target, event, weight=0.0, **kwargs):
        row = {"Дата среза": now, "Предыдущий срез": was,
               "Событие": event, "_вес": weight}
        row.update(kwargs)
        target.append(row)

    left = before.index.difference(after.index)
    joined = after.index.difference(before.index)
    stayed = before.index.intersection(after.index)

    # Перетасовка номеров рвёт историю тише, чем ломает: сравнение просто
    # покажет, что уволились все и пришли все. Проверяем это первым делом.
    turnover = (len(left) + len(joined)) / max(len(before), 1)
    if turnover > SHUFFLE_ALERT:
        add(other_rows, "⚠ Проверьте нумерацию",
            Было=len(before), Стало=len(after),
            Комментарий=(
                f"ушло {len(left)}, пришло {len(joined)} при составе "
                f"{len(before)} — если движение было не таким, значит "
                "идентификаторы сотрудников выданы заново. История сшивается "
                "по столбцу «Сотрудник»: номера должны быть неизменными "
                "между выгрузками."
            ))

    # --- события по людям: у каждого своя дельта, ФОТ проставим лесенкой ниже
    for person in sorted(left):
        row = before.loc[person]
        salary = 0.0 if pd.isna(row["ЗП"]) else float(row["ЗП"])
        add(people_rows, "Ушёл", weight=salary, Сотрудник=person,
            Блок=row["Блок"], Проект=row["Проект"], Продукт=row["Продукты"],
            Комментарий=f"{row['Проектная роль']}, {money_text(salary)}",
            **{"Δ руб": -salary})

    for person in sorted(joined):
        row = after.loc[person]
        salary = 0.0 if pd.isna(row["ЗП"]) else float(row["ЗП"])
        add(people_rows, "Пришёл", weight=salary, Сотрудник=person,
            Блок=row["Блок"], Проект=row["Проект"], Продукт=row["Продукты"],
            Комментарий=f"{row['Проектная роль']}, {money_text(salary)}",
            **{"Δ руб": salary})

    for person in sorted(stayed):
        old, new = before.loc[person], after.loc[person]

        if pd.notna(old["ЗП"]) and pd.notna(new["ЗП"]) and old["ЗП"] != new["ЗП"]:
            delta = float(new["ЗП"]) - float(old["ЗП"])
            own = round(100 * delta / old["ЗП"], 1) if old["ЗП"] else None
            add(people_rows, "ЗП изменилась", weight=abs(delta),
                Сотрудник=person, Блок=new["Блок"], Проект=new["Проект"],
                Продукт=new["Продукты"],
                Комментарий=(f"{money_text(old['ЗП'])} → {money_text(new['ЗП'])}"
                             + (f" ({own:+.1f}% к своей ЗП)" if own is not None
                                else "")),
                **{"Δ руб": round(delta, 2)})

        # Перестановки без денег: на ФОТ не влияют, но человека касаются,
        # поэтому идут тем же листом с нулевой дельтой.
        for field, event in (("Проектная роль", "Роль изменилась"),
                             ("Руководитель", "Руководитель изменился"),
                             ("Продукты", "Продукты изменились")):
            if old[field] != new[field]:
                add(people_rows, event, Сотрудник=person, Блок=new["Блок"],
                    Проект=new["Проект"], Продукт=new["Продукты"],
                    Комментарий=f"{old[field]} → {new[field]}",
                    **{"Δ руб": 0.0})

    # --- прочее: численность, вакансии, целостность
    def count_row(event, was_value, now_value):
        delta = now_value - was_value
        add(other_rows, event, weight=abs(delta),
            Было=was_value, Стало=now_value,
            **{"Δ руб": None,
               "Δ %": round(100 * delta / was_value, 1) if was_value else None})

    count_row("Сотрудников", len(before), len(after))
    count_row("Открытых вакансий",
              int((history[was]["Вакансия"] == 1).sum()),
              int((history[now]["Вакансия"] == 1).sum()))

    # Вакансии сравниваем по количеству одинаковых позиций: две открытые
    # ставки специалиста на одном продукте — это две строки, и закрытие одной
    # из них должно быть видно.
    before_v, after_v = vacancy_view(history[was]), vacancy_view(history[now])
    streaks = vacancy_streaks(history, until=now)
    for key in sorted(set(before_v.index) | set(after_v.index)):
        block, project, product, role = key
        old_n = int(before_v.get(key, 0))
        new_n = int(after_v.get(key, 0))
        common = {"Блок": block, "Проект": project, "Продукт": product}
        if new_n > old_n:
            add(other_rows, "Вакансия открыта", weight=new_n - old_n,
                Было=old_n, Стало=new_n, Комментарий=role, **common)
        elif new_n < old_n:
            add(other_rows, "Вакансия закрыта", weight=old_n - new_n,
                Было=old_n, Стало=new_n, Комментарий=role, **common)
        elif new_n and streaks.get(key, 1) >= 3:
            add(other_rows, "Вакансия висит", weight=streaks[key], Стало=new_n,
                Комментарий=f"{role} — открыта {streaks[key]} среза подряд",
                **common)

    if not people_rows:
        add(people_rows, "Изменений нет",
            Комментарий=f"состав и зарплаты среза {now} совпадают со срезом {was}",
            **{"Δ руб": 0.0})

    def order_by(rows_list):
        frame = pd.DataFrame(rows_list, columns=build)
        rank = {event: i for i, event in enumerate(EVENT_ORDER)}
        frame["_группа"] = frame["Событие"].map(rank).fillna(len(rank))
        frame = frame.sort_values(["_группа", "_вес"], ascending=[True, False])
        return frame.drop(columns=["_группа", "_вес"]).reset_index(drop=True)

    changes = order_by(people_rows)

    # Лесенка ФОТ: «Было» строки — фонд перед этим событием, «Стало» — после.
    # Порядок строк здесь уже окончательный, поэтому «Стало» последней строки
    # совпадает с ФОТ нового среза. Это и есть встроенная сверка.
    running = round(float(before["ЗП"].sum()), 2)
    was_col, now_col, pct_col = [], [], []
    for delta in changes["Δ руб"].fillna(0.0):
        nxt = round(running + float(delta), 2)
        was_col.append(running)
        now_col.append(nxt)
        pct_col.append(round(100 * float(delta) / running, 2) if running else None)
        running = nxt
    changes["Было"] = was_col
    changes["Стало"] = now_col
    changes["Δ %"] = pct_col

    return changes, order_by(other_rows)


def sheet_changes(
    history: dict[str, pd.DataFrame]
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Журнал изменений по всей истории, а не только за последний срез.

    Проходит по всем парам соседних срезов и склеивает результат: сверху
    самый свежий период, ниже предыдущие. Лесенка ФОТ считается внутри
    каждого периода отдельно, поэтому «Стало» последней строки периода
    равно ФОТ на дату этого периода.

    Периоды различаются парой столбцов «Дата среза» и «Предыдущий срез»:
    по ним же на дашборде вешается селектор, если нужен один период.
    """
    dates = sorted(history)
    if len(dates) < 2:
        first = pd.DataFrame([{
            "Дата среза": dates[-1] if dates else "",
            "Событие": "Первый срез",
            "Комментарий": "Сравнивать не с чем. Изменения появятся "
                           "со следующего запуска — храните папку history.",
        }], columns=CHANGE_COLUMNS)
        return first, first.copy()

    people_parts, other_parts = [], []
    # От свежего к старому: последнее изменение читают чаще всего.
    for was, now in reversed(list(zip(dates, dates[1:]))):
        people, other = changes_between(history, was, now)
        people_parts.append(people)
        other_parts.append(other)

    return (pd.concat(people_parts, ignore_index=True),
            pd.concat(other_parts, ignore_index=True))


def save_snapshot(assignments: pd.DataFrame, folder: Path, date: str) -> dict:
    """Кладёт срез в архив и возвращает всю историю: дата → таблица.

    Повторный запуск за ту же дату заменяет свой срез, а не добавляет второй:
    иначе двойной запуск за день задваивал бы месяц.
    """
    folder.mkdir(parents=True, exist_ok=True)
    assignments.to_csv(folder / f"{date}.csv", index=False, encoding="utf-8-sig")

    history = {}
    for path in sorted(folder.glob("*.csv")):
        try:
            history[path.stem] = read_snapshot(path)
        except Exception as error:      # noqa: BLE001 — архив правим руками
            print(f"Внимание: срез {path.name} не прочитан ({error}), пропускаю")
    return history


def sheet_checks(df: pd.DataFrame) -> pd.DataFrame:
    """Контроль качества данных. Всё, кроме первых строк, должно быть нулём."""
    people = df[df["Вакансия"] == 0]
    unique_people = people[people["Первичное назначение"] == 1]

    salary_conflicts = people.groupby("Сотрудник")["ЗП"].nunique()
    role_conflicts = people.groupby("Сотрудник")["Проектная роль"].nunique()
    org_conflicts = people[people["Организация"] != ""].groupby("Сотрудник")[
        "Организация"
    ].nunique()
    owners = df.groupby("Проект")["Блок"].nunique()
    # Дубли ищем по ПОЛНОМУ названию продукта, а не по короткому. Короткое
    # объединяет несколько систем в одну единицу учёта, и человек, который
    # ведёт и «Робот Макс», и «МПГУ» в одной роли, по короткому имени
    # выглядел бы задвоенным, хотя это две разные записи в исходнике.
    duplicates = df.groupby(
        ["Сотрудник", "Проект", "Продукт", "Проектная роль"]
    ).size()
    duplicates = duplicates[duplicates.index.get_level_values(0) != ""]

    checks = [
        ("Строк всего", len(df), "справочно"),
        ("Открытых вакансий", int(df["Вакансия"].sum()), "справочно"),
        ("Уникальных сотрудников", len(unique_people), "справочно"),
        ("Проектов", df["Проект"].nunique(), "справочно"),
        ("Продуктов", df["Продукт ключ"].nunique(),
         "справочно: единица учёта — «Продукт (кратко)»"),
        ("Продуктов без единого сотрудника",
         int(df["Продукт ключ"].nunique() - people["Продукт ключ"].nunique()),
         "держатся на одних вакансиях; в дереве видны с пометкой «0 чел»"),
        ("Полных названий продуктов", df["Продукт"].nunique(),
         "справочно: под одним коротким именем бывает несколько систем"),
        ("Проектных ролей", df["Проектная роль"].nunique(), "справочно"),
        ("В анализе справедливости", int(df["В анализе справедливости"].sum()),
         "справочно: без вакансий и ролей с плоским тарифом"),
        ("ЗП не подтверждена (людей)",
         int((unique_people["ЗП подтверждена"] == 0).sum()),
         "комментарий говорит, что числу верить нельзя"),
        ("ЗП пустая (строк)", int(people["ЗП"].isna().sum()), "должно быть 0"),
        ("Разные ЗП у одного сотрудника", int((salary_conflicts > 1).sum()),
         "должно быть 0: зарплата — атрибут человека"),
        ("Разные роли у одного сотрудника", int((role_conflicts > 1).sum()),
         "допустимо, если человек играет разные роли в разных продуктах"),
        ("Разные организации у одного сотрудника", int((org_conflicts > 1).sum()),
         "должно быть 0"),
        ("Проектов с несколькими блоками", int((owners > 1).sum()), "должно быть 0"),
        ("Дублей назначений", int((duplicates > 1).sum()), "должно быть 0"),
        ("Ролей вне классификатора", int((people["Уровень роли №"] == -1).sum()),
         "дополнить ROLE_LEVELS в скрипте"),
        ("Ролей без достаточной выборки",
         int((df[df["В анализе справедливости"] == 1]["Уровень сравнения"]
              != "Проектная роль").sum()),
         f"людей, сравниваемых по откату (в роли меньше {MIN_GROUP_SIZE} человек)"),
        ("Продуктов с одним человеком",
         int(df[df["Bus factor"] == "Критично: 1 человек"]["Продукт ключ"].nunique()),
         "риск незаменимости"),
        ("Выравнивание, руб/мес",
         round(unique_people["Доплата до порога"].sum(), 2),
         "сценарий C; A и B — на листе «Выравнивание · сводка»"),
        ("Расхождение ФОТ, руб",
         round(people["ФОТ аллоцированный"].sum() - unique_people["ЗП"].sum(), 2),
         "должно быть 0: ФОТ на листе «Проекты» минус сумма ЗП на листе «Сотрудники»"),
    ]
    return pd.DataFrame(checks, columns=["Проверка", "Значение", "Комментарий"])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "source", type=Path, nargs="?", default=DEFAULT_SOURCE,
        help=f"исходный .xlsx (по умолчанию {DEFAULT_SOURCE})",
    )
    parser.add_argument("--out", type=Path, default=Path("datalens_dataset"))
    parser.add_argument(
        "--sheet", default=None,
        help="имя или номер листа; по умолчанию определяется автоматически",
    )
    parser.add_argument(
        "--snapshot", default="",
        help="дата среза в формате ГГГГ-ММ-ДД; по умолчанию сегодняшняя. "
             "Указывайте явно, если пересобираете срез задним числом",
    )
    parser.add_argument(
        "--history", type=Path, default=None,
        help="папка с архивом срезов (по умолчанию history рядом с --out)",
    )
    parser.add_argument(
        "--no-history", action="store_true",
        help="не сохранять срез в архив и не считать лист «Изменения»",
    )
    args = parser.parse_args()

    if not args.source.exists():
        sys.exit(
            f"Файл не найден: {args.source}\n"
            f"Положите исходную выгрузку рядом со скриптом под именем {DEFAULT_SOURCE} "
            "или укажите путь первым аргументом."
        )

    sheet = int(args.sheet) if str(args.sheet).isdigit() else args.sheet
    print(f"Читаю: {args.source}")
    raw = load_source(args.source, sheet)

    assignments = build_assignments(raw)
    # Дата среза проставляется всегда: без неё архивный файл невозможно
    # опознать, а история сшивается именно по ней.
    snapshot = args.snapshot or dt.date.today().isoformat()
    try:
        dt.date.fromisoformat(snapshot)
    except ValueError:
        sys.exit(f"Дата среза «{snapshot}» не в формате ГГГГ-ММ-ДД")
    assignments["Дата среза"] = snapshot
    assignments = order_columns(assignments)

    csv_path = args.out.with_suffix(".csv")
    assignments.to_csv(csv_path, index=False, encoding="utf-8-sig")

    # Лист «Роли» отдельным файлом: одна строка на роль — ровно та
    # детализация, которая нужна чарту разброса («ящик с усами»).
    # Загружается в DataLens как второй датасет.
    roles_csv = args.out.with_name(args.out.stem + "_roles").with_suffix(".csv")
    sheet_roles(assignments).reset_index().to_csv(
        roles_csv, index=False, encoding="utf-8-sig"
    )

    # Лист «Иерархия» отдельным файлом: одна строка на пару «продукт —
    # сотрудник», показатели продукта повторяются. Из него строится дерево
    # структуры и выпадающий селектор «Сотрудник» на дашборде.
    tree_csv = args.out.with_name(args.out.stem + "_tree").with_suffix(".csv")
    tree = sheet_hierarchy(assignments)
    tree.reset_index().to_csv(tree_csv, index=False, encoding="utf-8-sig")

    # Поимённый список выравнивания отдельным файлом: он развёрнут по
    # сценариям, поэтому в DataLens подключается своим датасетом, а не
    # мешается с основной таблицей.
    align_summary, align_list = sheet_alignment(assignments)
    align_csv = args.out.with_name(args.out.stem + "_alignment").with_suffix(".csv")
    align_list.to_csv(align_csv, index=False, encoding="utf-8-sig")

    # Список сотрудников для селектора «Ручной ввод» — на случай, если
    # перезаливать файл в DataLens прямо сейчас не хочется: значения
    # вставляются в селектор списком. Селектор на основе датасета лучше,
    # он обновляется сам, но требует нового поля в датасете.
    staff_txt = args.out.with_name(args.out.stem + "_employees").with_suffix(".txt")
    staff_list = sorted(
        {name for name in tree["Сотрудник"] if str(name).strip()},
        key=lambda name: (len(str(name)), str(name)),
    )
    staff_txt.write_text("\n".join(staff_list) + "\n", encoding="utf-8")

    # Архив срезов и сравнение с предыдущим. Ценность появляется со второго
    # запуска, поэтому копить начинаем с первого.
    history: dict[str, pd.DataFrame] = {}
    changes = None
    other_changes = None
    if not args.no_history:
        folder = args.history or args.out.parent / "history"
        history = save_snapshot(assignments, folder, snapshot)
        changes, other_changes = sheet_changes(history)
        history_csv = args.out.with_name(args.out.stem + "_history").with_suffix(".csv")
        pd.concat(history.values(), ignore_index=True).to_csv(
            history_csv, index=False, encoding="utf-8-sig"
        )
        changes_csv = args.out.with_name(args.out.stem + "_changes").with_suffix(".csv")
        changes.to_csv(changes_csv, index=False, encoding="utf-8-sig")

    roles = sheet_roles(assignments)
    by_rating, by_role, by_project = sheet_rating(assignments)

    xlsx_path = args.out.with_suffix(".xlsx")
    with pd.ExcelWriter(xlsx_path, engine="openpyxl") as writer:
        assignments.to_excel(writer, sheet_name="Назначения", index=False)
        sheet_people(assignments).to_excel(writer, sheet_name="Сотрудники", index=False)

        # Три таблицы на одном листе, разделённые пустыми строками
        sheet = "Оценка ЗП"
        row = 0
        for title, table in (
            ("Сводка по категориям оценки", by_rating),
            ("Разбивка по проектным ролям", by_role),
            ("Разбивка по проектам", by_project),
        ):
            pd.DataFrame({title: []}).to_excel(writer, sheet_name=sheet, startrow=row)
            table.to_excel(writer, sheet_name=sheet, startrow=row + 1)
            row += len(table) + 4

        # Индекс разворачиваем в обычные столбцы: при записи многоуровневого
        # индекса Excel оставляет повторяющиеся значения пустыми, и DataLens
        # при импорте листа читает их как пропуски — дерево схлопывалось
        # в одну ветку, а группировки на листах «Роли» и «Проекты» ломались.
        roles.reset_index().to_excel(writer, sheet_name="Роли", index=False)
        sheet_projects(assignments).reset_index().to_excel(
            writer, sheet_name="Проекты", index=False
        )
        tree.reset_index().to_excel(writer, sheet_name="Иерархия", index=False)
        sheet_vacancies(assignments).to_excel(writer, sheet_name="Вакансии", index=False)

        # Выравнивание двумя листами: сводка и поимённый список. Связаны
        # ключом «Код сценария»; список развёрнут по вложенности сценариев,
        # поэтому итоги берутся только со сводки.
        align_summary.to_excel(
            writer, sheet_name="Выравнивание · сводка", index=False
        )
        align_list.to_excel(
            writer, sheet_name="Выравнивание · люди", index=False
        )

        if changes is not None:
            changes.to_excel(writer, sheet_name="Изменения", index=False)
            other_changes.to_excel(
                writer, sheet_name="Изменения · прочее", index=False
            )
        sheet_checks(assignments).to_excel(writer, sheet_name="Проверки", index=False)

    print(f"Записано: {csv_path}  ({len(assignments)} строк)")
    print(f"Записано: {roles_csv}  (по одной строке на роль, для чарта разброса)")
    print(f"Записано: {tree_csv}  ({len(tree)} строк: продукт × сотрудник, для иерархии)")
    print(f"Записано: {align_csv}  ({len(align_list)} строк: сценарий × сотрудник)")
    print(f"Записано: {staff_txt}  ({len(staff_list)} сотрудников для селектора)")
    if history:
        print(f"Записано: {history_csv}  ({len(history)} срезов, "
              f"{sum(len(x) for x in history.values())} строк)")
        print(f"Записано: {changes_csv}  ({len(changes)} событий)")
    print(f"Записано: {xlsx_path}")
    print()
    print("Сколько стоит выравнивание зарплат:")
    print(align_summary.to_string(index=False))
    if changes is not None and len(history) > 1:
        # В консоль — только последний период: лист содержит всю историю,
        # и общий счётчик по нему ничего не сказал бы о сегодняшнем запуске.
        latest = changes[changes["Дата среза"] == snapshot]
        print()
        print(f"Изменения с прошлого среза ({sorted(history)[-2]} → {snapshot}):")
        print(latest["Событие"].value_counts().to_string())
        if len(changes) > len(latest):
            print(f"Всего в журнале: {len(changes)} событий "
                  f"за {len(history) - 1} периодов")
    print()
    print(sheet_checks(assignments).to_string(index=False))

    # Проверка классификации ролей: медианы по уровням обязаны расти монотонно.
    # Если нет — уровень назначен неверно, и откат на него будет искажать базу.
    #
    # Печатаем медианы ролей, сгруппированные по уровням, а не отдельное число
    # «медиана уровня»: последнее в расчётах не участвует (база отката берётся
    # по соседним ролям), и рядом с похожей медианой роли только путает.
    scored = assignments[assignments["В анализе справедливости"] == 1]
    print()
    print("Медианы ЗП по ролям (то, с чем сравнивается зарплата):")
    print(
        scored.groupby(["Уровень роли №", "Уровень роли", "Проектная роль"])["ЗП"]
        .agg(людей="count", медиана="median")
        .round(2)
        .to_string()
    )

    level_medians = scored.groupby("Уровень роли №")["ЗП"].median().tolist()
    monotone = all(a <= b for a, b in zip(level_medians, level_medians[1:]))
    print(
        "Монотонность уровней:",
        "ОК" if monotone else "НАРУШЕНА — проверьте ROLE_LEVELS",
    )

    print()
    print("Оценка зарплат (относительно медианы проектной роли):")
    print(by_rating[["людей", "доля, %", "подтверждённых_ЗП", "сумма_отклонения"]].to_string())


if __name__ == "__main__":
    main()
