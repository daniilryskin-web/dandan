"""
Тест (v54.2): сравнение по БЫТОВОЙ ТЕХНИКЕ и ЭЛЕКТРОНИКЕ.

На прогоне по технике карточки «аэрогриль/хлебопечка/гриль/кухонный комбайн…»
не относились ни к одной категории (словарь был «одёжный») → «низкое совпадение»
→ масса ложных «ПРОВЕРИТЬ ВРУЧНУЮ». Плюс баг: термины в единственном числе
(«обогреватель», «кофеварка») не совпадали с множественным («обогревателИ»,
«кофеваркИ»), а «электро-составные» («электроводонагреватель») — со своим корнем.

Запуск:  python3 tests/test_appliances.py
"""
import sys
import types
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.modules.setdefault("webview", types.ModuleType("webview"))

import main_v39 as m  # noqa: E402

RESULTS = []


def check(name, cond):
    RESULTS.append(bool(cond))
    print(f"{'PASS' if cond else 'FAIL'}  {name}")


def v(pn, cert):
    return m.compare_product_names(pn, cert, "", "", "Действует")[0]


def main():
    # --- карточки техники распознаются как appliances/electronics ---
    appl_cards = ["Аэрогриль 7L", "Хлебопечка с замесом теста", "Гриль электрический для дома",
                  "Кухонный комбайн с нарезкой", "Электрогриль с открытием 180",
                  "Встраиваемая морозильная камера", "Инверторная сплит-система ELYSIUM",
                  "Конвектор электрический Cube", "Водонагреватель 10 л бойлер",
                  "Электровафельница RK-WB3", "Кофемашина рожковая", "Мультиварка 5 литров"]
    for c in appl_cards:
        check(f"техника распознана: {c!r}", "appliances" in m._detect_categories(c))

    elec_cards = ["Мышка беспроводная для компьютера", "Наушники TWS", "Зарядка для телефона",
                  "Повербанк 20000", "Смарт-часы мужские", "Колонка портативная"]
    for c in elec_cards:
        check(f"электроника распознана: {c!r}", "electronics" in m._detect_categories(c))

    # --- множественное число и электро-составные в СЕРТИФИКАТАХ ---
    for cert in ["Обогреватели электрические бытовые", "Гейзерные кофеварки алюминиевые",
                 "Электроводонагреватели аккумуляционные бытовые", "Компьютерные мыши",
                 "Кондиционеры воздуха (сплит-системы) бытовые"]:
        check(f"серт распознан: {cert!r}",
              bool(m._detect_categories(cert) & {"appliances", "electronics", "kitchenware"}))

    # --- сравнение: техника vs общий технический сертификат → OK ---
    check("аэрогриль vs «приборы бытового назначения для приготовления пищи» → OK",
          v("Аэрогриль электрический 8 л", "Электрические приборы бытового назначения для приготовления пищи: аэрогрили") == "OK")
    check("хлебопечка vs общий бытовой серт → OK",
          v("Хлебопечка с замесом теста SA-7509B", "Электрические приборы бытового назначения для приготовления пищи: хлебопечи") == "OK")
    check("сплит-система vs кондиционеры бытовые → OK",
          v("Инверторная сплит-система ELYSIUM NERO", "Кондиционеры воздуха (сплит-системы) бытовые, внутренний блок") == "OK")
    check("обогреватель/конвектор vs обогреватели бытовые → OK",
          v("Конвектор электрический Cube NCC-2000", "Обогреватели электрические бытовые, конвекционного типа") == "OK")
    check("мышка vs компьютерные мыши → OK",
          v("Мышка беспроводная для компьютера и ноутбука", "Компьютерные мыши торговой марки iEasy") == "OK")

    # --- БЕЗОПАСНОСТЬ: техника vs ЧУЖОЙ сертификат остаётся НЕСООТВЕТСТВИЕ ---
    check("мультиварка vs ручной инструмент → НЕСООТВЕТСТВИЕ",
          v("Мультиварка 5 литров 12 программ", "Инструмент ручной пневматический торговых марок") == "НЕСООТВЕТСТВИЕ")
    check("блок питания vs одежда → НЕСООТВЕТСТВИЕ",
          v("Блок питания на 35W для iPhone", "Одежда верхняя швейная второго слоя для женщин") == "НЕСООТВЕТСТВИЕ")


if __name__ == "__main__":
    main()
    p, t = sum(RESULTS), len(RESULTS)
    print("-" * 60)
    print(f"ИТОГО: {p}/{t} прошло")
    sys.exit(0 if p == t else 1)
