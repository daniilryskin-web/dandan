"""
Тест (issue v52): устранение ЛОЖНЫХ «ПРОВЕРИТЬ ВРУЧНУЮ» по одежде.

На прогоне 50k множество реальных товаров не распознавалось (тельняшка,
кальсоны, олимпийка, слип, дождевик, термо-*, шапочки, словоформы «Пижам»,
«белья», «шортами»), из-за чего корректные совпадения уходили в ручную проверку.
Здесь проверяем:
  • новые виды одежды распознаются (category/subtype/layer);
  • широкий сертификат (3+ вида / несколько слоёв / общая детская группа)
    НЕ даёт ложный конфликт слоя → OK, а не ручная проверка;
  • узкий сертификат другого вида по-прежнему НЕ даёт ложный OK (безопасность);
  • реальные конфликты (детское vs взрослый, одежда vs игрушки) сохраняются.

Запуск:  python3 tests/test_compare_v52.py
"""
import sys
import types
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.modules.setdefault("webview", types.ModuleType("webview"))

import main_v39 as m  # noqa: E402

RESULTS = []


def check(name, cond):
    RESULTS.append(bool(cond))
    print(f"{'PASS' if cond else 'FAIL'}  {name}")


def verdict(pn, cert, age="Действует"):
    return m.compare_product_names(pn, cert, "", "", age)[0]


def main():
    # --- новые виды одежды распознаются как ОДЕЖДА ---
    for w in ("Тельняшка детская", "Кальсоны мужские", "Олимпийка женская",
              "Слип для новорожденных", "Термолонгслив детский", "Туника летняя",
              "Пижам с шортами", "Синий комплект белья", "Шортами летними"):
        check(f"одежда распознана: {w!r}", "clothing" in m._detect_categories(w))
    # «слип» — одежда, но «слипоны» — обувь (не путаем)
    check("слипоны — это обувь, а не бельё",
          "clothing" not in m._detect_categories("Слипоны кожаные")
          and "footwear" in m._detect_categories("Слипоны кожаные"))
    # обувь-диминутивы
    for w in ("Полусапожки летние", "Босоножки женские", "Туфельки детские"):
        check(f"обувь распознана: {w!r}", "footwear" in m._detect_categories(w))

    # --- слои новых видов ---
    check("тельняшка → первый слой", "first_layer" in m._detect_layers("тельняшка"))
    check("олимпийка → второй слой", "second_layer" in m._detect_layers("олимпийка"))
    check("дождевик → третий слой", "third_layer" in m._detect_layers("дождевик"))
    check("шапочки → головной убор", "headwear" in m._detect_layers("шапочки летние"))

    # --- широкий сертификат покрывает разные виды → OK (а не ручная проверка) ---
    broad_first = ("Изделия трикотажные бельевые первого слоя мужские и женские, "
                   "из пряжи: брюки, толстовки, футболки, костюмы")
    for pn in ("Спортивные штаны оверсайз", "Шорты спортивные", "Свитшот повседневный"):
        check(f"широкий бельевой сертификат покрывает {pn!r} → OK",
              verdict(pn, broad_first) == "OK")
    broad_child = ("Изделия трикотажные бельевые первого слоя для детей дошкольной, "
                   "школьной возрастных групп")
    for pn in ("Тельняшка детская", "Слип для новорожденных", "Термолонгслив для мальчика"):
        check(f"широкий детский сертификат покрывает {pn!r} → OK",
              verdict(pn, broad_child) == "OK")

    # --- БЕЗОПАСНОСТЬ: узкий сертификат другого вида НЕ даёт ложный OK ---
    check("узкие трусы (первый слой) vs платье → НЕ OK",
          verdict("Платье женское вечернее",
                  "Трусы трикотажные бельевые первого слоя женские") != "OK")
    # --- реальные конфликты сохраняются ---
    check("детская куртка vs игрушки → НЕСООТВЕТСТВИЕ",
          verdict("Куртка детская зимняя", "Игрушки мягкие набивные") == "НЕСООТВЕТСТВИЕ")
    check("кроссовки vs смартфон → НЕСООТВЕТСТВИЕ",
          verdict("Кроссовки мужские", "Смартфон Samsung Galaxy") == "НЕСООТВЕТСТВИЕ")
    check("детское vs сертификат строго для взрослых → НЕСООТВЕТСТВИЕ",
          verdict("Слип для новорожденных",
                  "Изделия трикотажные второго слоя для взрослых из хлопка") == "НЕСООТВЕТСТВИЕ")


if __name__ == "__main__":
    main()
    p, t = sum(RESULTS), len(RESULTS)
    print("-" * 60)
    print(f"ИТОГО: {p}/{t} прошло")
    sys.exit(0 if p == t else 1)
