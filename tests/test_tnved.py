"""
Тест (улучшение №2, v53): сверка по коду ТН ВЭД ЕАЭС.

Код ТН ВЭД — независимый от названия признак товара. Проверяем:
  • префиксы кодов корректно отображаются в товарные категории;
  • поле-дамп кодов («КОД ТН ВЭД: …») больше не тупик — сравниваем по категории;
  • код другой группы создаёт конфликт (9503 игрушки vs посуда);
  • коды вне карты → честно «не удалось извлечь».

Запуск:  python3 tests/test_tnved.py
"""
import sys
import types
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.modules.setdefault("webview", types.ModuleType("webview"))

import main_v39 as m  # noqa: E402

RESULTS = []


def check(name, cond):
    RESULTS.append(bool(cond))
    print(f"{'PASS' if cond else 'FAIL'}  {name}")


def verdict(pn, cert, tnved=""):
    return m.compare_product_names(pn, cert, "", "", "Действует", cert_tnved=tnved)[0]


def main():
    # --- карта префиксов ---
    cases = [
        ("6107110000", "clothing"), ("6203191000", "clothing"),
        ("6402990000", "footwear"), ("6405000000", "footwear"),
        ("9503001000", "toys"), ("8517120000", "electronics"),
        ("8518300000", "electronics"), ("8516600000", "appliances"),
        ("7323930000", "kitchenware"), ("3304990000", "cosmetics"),
        ("6505003000", "accessories"), ("6302100000", "home_textile"),
        ("7201000000", ""),  # глава вне карты
        ("12", ""), ("", ""),
    ]
    for code, exp in cases:
        got = m._tnved_category(code)
        check(f"ТН ВЭД {code!r} → {exp or '∅'}", got == exp)

    # --- категории из текста-дампа кодов ---
    cats = m._tnved_categories_from_text("КОД ТН ВЭД ЕАЭС: 6107110000, 6107120000")
    check("из текста кодов извлечена категория clothing", cats == {"clothing"})

    # --- поведение в сравнении ---
    check("коды-одежда + карточка-одежда → OK (раньше «не извлечено»)",
          verdict("Джинсовый комбинезон детский",
                  "КОД ТН ВЭД ЕАЭС: 6203191000, 6203199000", "6203191000") == "OK")
    check("код=игрушки vs карточка-посуда → НЕСООТВЕТСТВИЕ",
          verdict("Кастрюля эмалированная",
                  "КОД ТН ВЭД ЕАЭС: 9503001000", "9503001000") == "НЕСООТВЕТСТВИЕ")
    check("коды вне карты → НЕ УДАЛОСЬ ИЗВЛЕЧЬ",
          verdict("Носки детские", "КОД ТН ВЭД ЕАЭС: 7201000000", "7201000000")
          == "НЕ УДАЛОСЬ ИЗВЛЕЧЬ НАЗВАНИЕ ИЗ РЕЕСТРА")
    check("код подтверждает категорию → OK даже при слабом тексте",
          verdict("Наушники беспроводные", "Аппаратура", "8518300000") == "OK")
    # код НЕ ломает корректные текстовые вердикты (безопасность)
    check("код не создаёт ложный OK для конфликта вид/категория",
          verdict("Платье вечернее", "Смартфон Samsung", "8517120000") == "НЕСООТВЕТСТВИЕ")


if __name__ == "__main__":
    main()
    p, t = sum(RESULTS), len(RESULTS)
    print("-" * 60)
    print(f"ИТОГО: {p}/{t} прошло")
    sys.exit(0 if p == t else 1)
