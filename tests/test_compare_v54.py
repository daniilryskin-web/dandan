"""
Тест (v54): устранение ложных НЕСООТВЕТСТВИЙ на большом прогоне «одежда для детей».

Чинит конкретные ложные конфликты, найденные в результатах:
  • сумка/кросс-боди/чехол для телефона vs «Кожгалантерейные изделия» → OK
    (кожгалантерея = аксессуары; раньше «другая группа» из-за случайных слов
    «косметички»/«в виде игрушек» в длинном перечне сертификата);
  • «Body Paint парфюмерная вода» (косметика) vs парфюм-сертификат → OK
    (раньше «боди» → одежда);
  • мягконабивная игрушка «Кот Басик в костюме», надувной «жилет для плавания»
    → игрушки, а не одежда → OK;
  • подростковое/школьное vs сертификат «для взрослых» — НЕ жёсткое
    несоответствие (размеры пересекаются) → OK при совпадении вида или
    ПРОВЕРИТЬ ВРУЧНУЮ;
  • детское постельное бельё vs «бельё для взрослых» — размер, не тех.регламент → OK.

БЕЗОПАСНОСТЬ (остаётся НЕСООТВЕТСТВИЕ):
  • малыши/новорождённые в одежде vs сертификат для взрослых (ТР ТС 007 vs 017);
  • одежда vs пищевая продукция/обувь.

Запуск:  python3 tests/test_compare_v54.py
"""
import sys
import types
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.modules.setdefault("webview", types.ModuleType("webview"))

import main_v39 as m  # noqa: E402

RESULTS = []


def check(name, cond):
    RESULTS.append(bool(cond))
    print(f"{'PASS' if cond else 'FAIL'}  {name}")


def v(pn, cert, tnved=""):
    return m.compare_product_names(pn, cert, "", "", "Действует", cert_tnved=tnved)[0]


def main():
    # --- кожгалантерея распознаётся как аксессуары ---
    check("кожгалантерея → accessories", "accessories" in m._detect_categories("Кожгалантерейные изделия мужские и женские"))
    check("парфюм → cosmetics", "cosmetics" in m._detect_categories("Парфюмерная вода"))

    # --- ложные конфликты больше не несоответствие ---
    bag_cert = ("Изделия кожгалантерейные для детей и подростков: сумки, рюкзаки, "
                "сумочки для косметики, чехлы для телефонов, рюкзаки в виде игрушек")
    check("сумка/чехол vs кожгалантерея → НЕ несоответствие",
          v("Сумка для телефона через плечо кросс боди мальчику", bag_cert) != "НЕСООТВЕТСТВИЕ")
    check("кросс-боди vs кожгалантерея → OK",
          v("Сумка кросс-боди маленькая через плечо", "Кожгалантерейные изделия мужские и женские") == "OK")
    check("Body Paint парфюм vs косметика → НЕ несоответствие",
          v("Body Paint Боди Пейнт парфюмерная вода 20 мл", "Продукция парфюмерно-косметическая: Парфюмерная вода") != "НЕСООТВЕТСТВИЕ")
    check("мягконабивная игрушка «в костюме» vs игрушки → НЕ несоответствие",
          v("Кот Басик Baby 20 см в костюме спорт-шик", "Игрушки мягконабивные для детей до трех лет") != "НЕСООТВЕТСТВИЕ")
    check("надувной жилет для плавания vs водные игрушки → НЕ несоответствие",
          v("Жилет для плавания детский надувной плавательный", "Игрушки надувные для игры на воде, бассейны") != "НЕСООТВЕТСТВИЕ")

    # --- подростковое/школьное vs взрослый сертификат — не жёсткое ---
    check("школьные шорты vs «для взрослых» → не несоответствие",
          v("Шорты классические школьные офисные летние", "Изделия швейные второго слоя для взрослых из хлопка") != "НЕСООТВЕТСТВИЕ")
    check("подростковые джинсы vs женский серт → не несоответствие",
          v("Джинсы широкие подростковые багги", "Костюмы женские; Брюки женские") != "НЕСООТВЕТСТВИЕ")
    check("детское постельное бельё vs «для взрослых» → не несоответствие",
          v("Детское постельное белье в кроватку хлопок", "Белье постельное для взрослых из хлопчатобумажных тканей") != "НЕСООТВЕТСТВИЕ")

    # --- БЕЗОПАСНОСТЬ: реальные несоответствия сохраняются ---
    check("малыш/новорождённый в одежде vs «для взрослых» → НЕСООТВЕТСТВИЕ",
          v("Распашонка для новорожденных муслин", "Изделия верхние швейные второго слоя мужские и женские") == "НЕСООТВЕТСТВИЕ")
    check("детская одежда vs пищевая продукция → НЕСООТВЕТСТВИЕ",
          v("Ползунки для новорожденных велюр", "Пищевая продукция. Молочные продукты. Сливки") == "НЕСООТВЕТСТВИЕ")
    check("детская сорочка vs женский серт → НЕСООТВЕТСТВИЕ (007 vs 017)",
          v("Ночная сорочка детская хлопок", "Изделия трикотажные первого слоя женские сорочки и пижамы") == "НЕСООТВЕТСТВИЕ")
    check("одежда vs обувь → НЕСООТВЕТСТВИЕ",
          v("Свитшот оверсайз толстовка", "Обувь повседневная мужская и женская с верхом из текстиля") == "НЕСООТВЕТСТВИЕ")


if __name__ == "__main__":
    main()
    p, t = sum(RESULTS), len(RESULTS)
    print("-" * 60)
    print(f"ИТОГО: {p}/{t} прошло")
    sys.exit(0 if p == t else 1)
