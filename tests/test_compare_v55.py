"""
Тест (v54.5): устранение МАССОВЫХ ложных «НЕСООТВЕТСТВИЕ» и «ПРОВЕРИТЬ ВРУЧНУЮ»,
найденных на большом прогоне (63k строк). Первопричина — детектор категорий
срабатывал по ОДНОМУ случайному слову и generic-disjoint превращал это в жёсткое
несоответствие:
  • «Музыкальный детский ТЕЛЕФОН» → electronics vs сертификат «Игрушки» → ложь;
  • «бюстгальтер … ЧАШКами» → kitchenware vs «изделия корсетные» → ложь;
  • «фигурки домашние ЖИВОТНЫЕ» → pet, «игровая КУХНЯ» → food vs «Игрушки» → ложь;
  • карнавальные костюмы/маски vs «Изделия для карнавалов» (это игрушки) → ложь;
  • «Аквамозаика»/«Колонка bluetooth» уходили в «ПРОВЕРИТЬ ВРУЧНУЮ».

Правки (по согласованию с пользователем):
  • generic-disjoint → жёсткое НЕСООТВЕТСТВИЕ ТОЛЬКО для доказанных пар
    (одежда/обувь vs твёрдые товары; прибор vs инструмент), прочее → ВРУЧНУЮ;
  • сертификат на игрушки / карнавал покрывает игрушечный/костюмный листинг → OK;
  • детектор: бельё/корсетные → clothing; аудиооборудование → electronics.

БЕЗОПАСНОСТЬ (должно ОСТАТЬСЯ НЕСООТВЕТСТВИЕ):
  • реальная одежда vs обувь / электроника / игрушки / пищёвка / прибор vs инструмент;
  • детская одежда (вкл. школьную) vs сертификат для взрослых (ТР ТС 007 vs 017).

Запуск:  python3 tests/test_compare_v55.py
"""
import sys
import types
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.modules.setdefault("webview", types.ModuleType("webview"))

import main_v39 as m  # noqa: E402

RESULTS = []


def check(name, cond):
    RESULTS.append(bool(cond))
    print(f"{'PASS' if cond else 'FAIL'}  {name}")


def v(pn, cert):
    return m.compare_product_names(pn, cert, "", "", "Действует")[0]


def main():
    # --- детектор: бельё/корсетные → одежда (а не kitchenware из-за «чашк») ---
    check("бюстгальтер → clothing", "clothing" in m._detect_categories("Бесшовный бюстгальтер со съемными чашками"))
    check("аудиооборудование → electronics", "electronics" in m._detect_categories("Аудиооборудование бытового назначения"))

    # --- БЫЛО ложное НЕСООТВЕТСТВИЕ → теперь НЕ несоответствие ---
    toy = "Игрушки для детей старше трех лет из полимерных материалов, в т.ч. с текстилем"
    check("игрушка-телефон vs игрушки → не несоответствие",
          v("Музыкальный детский телефон Динозаврик", toy) != "НЕСООТВЕТСТВИЕ")
    check("фигурки животных vs игрушки → не несоответствие",
          v("Набор фигурок домашние животные", toy) != "НЕСООТВЕТСТВИЕ")
    check("игровая кухня vs игрушки → не несоответствие",
          v("Детская игровая кухня с водой и паром", toy) != "НЕСООТВЕТСТВИЕ")
    check("бюстгальтер vs корсетные изделия → не несоответствие",
          v("Молочный бюстгальтер с треугольными чашками", "Изделия корсетные первого слоя для женщин из хлопка") != "НЕСООТВЕТСТВИЕ")
    check("карнавальный костюм vs изделия для карнавалов → не несоответствие",
          v("Костюм Медсестры для девочки шапочка фартук сумка", "Изделия для праздников и карнавалов для детей старше трех лет") != "НЕСООТВЕТСТВИЕ")
    check("карнавальная маска vs игрушки для карнавалов → не несоответствие",
          v("Маска тигра карнавальная", "Игрушки для праздников и карнавалов для детей старше трех лет") != "НЕСООТВЕТСТВИЕ")

    # --- БЫЛО ложное ПРОВЕРИТЬ ВРУЧНУЮ → теперь OK (доказанное покрытие) ---
    check("аквамозаика vs игрушки → OK",
          v("Аквамозаика для детей Насекомые 230 бусин", toy) == "OK")
    # «Интерактивный щенок» без игрушечного слова и без детского маркера —
    # безопасно НЕ обвинять (не несоответствие); авто-OK не выдаём (решение «спорное
    # → вручную»). Главное — ушло ложное НЕСООТВЕТСТВИЕ.
    check("интерактивный щенок vs игрушки → не несоответствие",
          v("Интерактивный щенок", "Игрушки для детей старше трех лет из текстильных материалов") != "НЕСООТВЕТСТВИЕ")
    check("колонка bluetooth vs аудиооборудование → OK",
          v("Колонка беспроводная bluetooth с подсветкой", "Аудиооборудование бытового назначения: перечень моделей") == "OK")

    # --- точечные фиксы детектора (крупные кластеры ложных несоответствий) ---
    check("электрочайник vs электроприборы → не несоответствие",
          v("Чайник электрический металлический 2.3 л", "Электрические приборы бытового назначения: электрочайники") != "НЕСООТВЕТСТВИЕ")
    check("дезодорант vs антиперспирант-карандаш → не несоответствие",
          v("Дезодорант стик женский Сухость пудры 40 мл", "Антиперспирант-карандаш Dove Go Fresh") != "НЕСООТВЕТСТВИЕ")
    check("полукомбинезон спортивный vs одежда → не несоответствие",
          v("Полукомбинезон утепленный спортивный", "Одежда верхняя швейная третьего слоя для детей старше") != "НЕСООТВЕТСТВИЕ")
    check("наушники vs аудио-видеоаппаратура → не несоответствие",
          v("Наушники проводные CX300S", "аудио- и видеоаппаратура, приемники теле- и радиовещания") != "НЕСООТВЕТСТВИЕ")
    # SAFETY: заварочный (неэлектрический) чайник не стал прибором ложно
    check("заварочный чайник vs посуда → не несоответствие",
          v("Заварочный чайник керамический", "Посуда из стекла термостойкого") != "НЕСООТВЕТСТВИЕ")
    # SAFETY: прибор vs посуда остаётся конфликтом (детектор не «породнил» категории)
    check("машинка для катышков vs детская посуда → НЕСООТВЕТСТВИЕ",
          v("Машинка для удаления катышков", "Детская посуда из пластика") == "НЕСООТВЕТСТВИЕ")

    # --- доказанное покрытие toy-cert НЕ распространяется на реальную одежду/обувь ---
    check("платье женское vs игрушки → НЕСООТВЕТСТВИЕ (одежда, не toy-cover)",
          v("Платье женское вечернее", "Игрушки мягконабивные для детей до трех лет") == "НЕСООТВЕТСТВИЕ")

    # --- БЕЗОПАСНОСТЬ: реальные несоответствия сохраняются ---
    check("блок питания vs одежда → НЕСООТВЕТСТВИЕ",
          v("Блок питания на 35W для iPhone", "Одежда верхняя швейная второго слоя для женщин") == "НЕСООТВЕТСТВИЕ")
    check("свитшот vs обувь → НЕСООТВЕТСТВИЕ",
          v("Свитшот оверсайз толстовка", "Обувь повседневная мужская и женская с верхом из текстиля") == "НЕСООТВЕТСТВИЕ")
    check("мультиварка vs пневмоинструмент → НЕСООТВЕТСТВИЕ",
          v("Мультиварка 5 литров 12 программ", "Инструмент ручной пневматический торговых марок") == "НЕСООТВЕТСТВИЕ")
    check("школьные шорты vs «для взрослых» → НЕСООТВЕТСТВИЕ (возраст не трогали)",
          v("Шорты классические школьные офисные летние", "Изделия швейные второго слоя для взрослых из хлопка") == "НЕСООТВЕТСТВИЕ")
    check("детская одежда vs пищевая продукция → НЕСООТВЕТСТВИЕ",
          v("Ползунки для новорожденных велюр", "Пищевая продукция. Молочные продукты. Сливки") == "НЕСООТВЕТСТВИЕ")

    # --- спорное (нечёткое распознавание, конфликт не доказан) → ВРУЧНУЮ, не ложь ---
    check("весы напольные vs весы торговые (детектор расходится) → не несоответствие",
          v("Весы напольные торговые 150 кг ВПН-150 УБ", "Весы торговые электронные для взвешивания товаров и продуктов") != "НЕСООТВЕТСТВИЕ")


if __name__ == "__main__":
    main()
    p, t = sum(RESULTS), len(RESULTS)
    print("-" * 60)
    print(f"ИТОГО: {p}/{t} прошло")
    sys.exit(0 if p == t else 1)
