"""
Регрессионный тест логики сравнения: ОБУВЬ не должна совпадать с сертификатом
на ОДЕЖДУ/БЕЛЬЁ.

Баг: слипоны/тапочки-слипоны ложно классифицировались как «бельё» (синоним
«слип» совпадал по началу слова со «слипоны»), из-за чего обувь получала OK
против бельевого сертификата. Теперь слипоны — это обувь (footwear), и сравнение
с одеждой даёт НЕСООТВЕТСТВИЕ. При этом настоящая детская одежда/бельё
(боди, слип-комбинезон, песочник, футболка) с бельевым сертификатом — OK.

Запуск:  python3 tests/test_compare_footwear.py
"""
import sys
import types
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.modules.setdefault("webview", types.ModuleType("webview"))
import main_v39 as m  # noqa: E402

RESULTS = []
CERT_BELYE = ("Изделия бельевые трикотажные первого слоя для детей от 1 до 3 лет: "
              "ползунки, песочники, футболки, шорты")
CERT_SHOES_ADULT = ("Обувь повседневная, в том числе для активного отдыха, для взрослых, "
                    "с верхом из искусственной кожи, из текстильных материалов")
CERT_SHOES_KIDS = ("Обувь детская повседневная (ясельная с закрытой пяточной частью, "
                   "малодетская и дошкольная с фиксированной пяточной частью, школьная)")


def check(name, got, exp):
    ok = got == exp
    RESULTS.append(ok)
    print(f"{'PASS' if ok else 'FAIL'}  {name}: {got} (ожид. {exp})")


def verdict(card, cert):
    return m.compare_product_names(card, cert, doc_status="Действует")[0]


# слипоны теперь — обувь
check("слипоны -> footwear", "footwear" in m._detect_categories("слипоны") and
      "clothing" not in m._detect_categories("слипоны"), True)

# ОБУВЬ vs БЕЛЬЁ-сертификат -> НЕСООТВЕТСТВИЕ (был ложный OK)
for card in ["Тапочки детские в садик слипоны с мехом",
             "Слипоны детские тапочки закрытые на липучке",
             "Сандалии детские летние", "Кроссовки детские на липучке"]:
    check(f"обувь×бельё «{card[:30]}»", verdict(card, CERT_BELYE), "НЕСООТВЕТСТВИЕ")

# Детская обувь vs ВЗРОСЛАЯ обувь -> НЕСООТВЕТСТВИЕ (возрастной конфликт)
check("дет.обувь × взрослая обувь", verdict("Туфли для девочки", CERT_SHOES_ADULT), "НЕСООТВЕТСТВИЕ")

# Детская обувь vs детская обувь -> OK
check("дет.обувь × дет.обувь", verdict("Сандалии детские летние на липучке", CERT_SHOES_KIDS), "OK")

# Настоящая детская одежда/бельё vs бельё-сертификат -> OK (не сломали)
for card in ["Боди детское ползунки", "Слип-комбинезон детский ясельный",
             "Песочник детский", "Футболка детская"]:
    check(f"одежда×бельё «{card}»", verdict(card, CERT_BELYE), "OK")

if __name__ == "__main__":
    p, t = sum(RESULTS), len(RESULTS)
    print("-" * 60)
    print(f"ИТОГО: {p}/{t} прошло")
    sys.exit(0 if p == t else 1)
